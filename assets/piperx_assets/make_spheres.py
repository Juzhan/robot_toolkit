"""Generate ``piper_x_spheres.json`` (collision spheres per link) from the URDF meshes.

Offline tool (needs trimesh); the runtime guard only reads the JSON. Each link's
surface is sampled and clustered with k-means; every cluster becomes the
smallest centroid sphere containing its samples, so all samples are covered.
The prismatic fingers are folded into ``gripper_base`` over their full stroke.

    PYTHONPATH=<dir containing robot_toolkit> python robot_toolkit/assets/piperx_assets/make_spheres.py
"""

import json
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
import trimesh

from robot_toolkit.core.collision import _transform

HERE = Path(__file__).resolve().parent
URDF = HERE / 'assets' / 'piper_x.urdf'
MAX_RADIUS = .035


def kmeans_spheres(points, max_radius, rng):
    for k in range(1, 40):
        centers = points[rng.choice(len(points), k, replace=False)]
        for _ in range(30):
            label = np.argmin(np.linalg.norm(points[:, None] - centers[None], axis=-1), axis=1)
            centers = np.array([points[label == i].mean(0) if np.any(label == i) else centers[i]
                                for i in range(k)])
        label = np.argmin(np.linalg.norm(points[:, None] - centers[None], axis=-1), axis=1)
        radii = np.array([np.linalg.norm(points[label == i] - centers[i], axis=1).max()
                          if np.any(label == i) else 0. for i in range(k)])
        if radii.max() <= max_radius:
            break
    return [(c, r) for c, r in zip(centers, radii) if r > 0]


def main():
    rng = np.random.default_rng(0)
    root = ET.parse(URDF).getroot()
    clouds = {}
    for link in root.findall('link'):
        mesh = link.find('collision/geometry/mesh')
        if mesh is not None:
            surface = trimesh.load(URDF.parent / mesh.get('filename'))
            samples, _ = trimesh.sample.sample_surface(surface, 3000, seed=0)
            clouds[link.get('name')] = np.vstack([samples, surface.vertices[::5]])
    for joint in root.findall('joint'):
        if joint.get('type') != 'prismatic':
            continue
        origin = joint.find('origin')
        offset = _transform([float(v) for v in origin.get('xyz').split()],
                            [float(v) for v in origin.get('rpy').split()])
        axis = np.array([float(v) for v in joint.find('axis').get('xyz').split()])
        limit = joint.find('limit')
        child = clouds.pop(joint.find('child').get('link'))
        for travel in np.linspace(float(limit.get('lower')), float(limit.get('upper')), 5):
            moved = child + axis * travel
            parent = joint.find('parent').get('link')
            clouds[parent] = np.vstack([clouds[parent],
                                        moved @ offset[:3, :3].T + offset[:3, 3]])
    spheres = {}
    for name, points in clouds.items():
        spheres[name] = [{'center': np.round(c, 4).tolist(), 'radius': round(float(r) + 5e-4, 4)}
                         for c, r in kmeans_spheres(points, MAX_RADIUS, rng)]
        print(name, len(spheres[name]), 'spheres, max r',
              max(s['radius'] for s in spheres[name]))
    data = {'urdf': 'assets/piper_x.urdf', 'base_link': 'base_link',
            'joints': [f'joint{i}' for i in range(1, 7)],
            'note': 'generated by make_spheres.py; unpadded (add padding_m at load)',
            'spheres': spheres}
    (HERE / 'piper_x_spheres.json').write_text(json.dumps(data, indent=1))


if __name__ == '__main__':
    main()
